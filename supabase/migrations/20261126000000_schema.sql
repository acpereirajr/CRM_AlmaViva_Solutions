-- ---------------------------------------------------------------------------
-- Perfis: liga cada usuário do Supabase Auth a um papel e ao nome do gerente
-- ---------------------------------------------------------------------------
create table if not exists public.perfis (
  user_id   uuid primary key references auth.users(id) on delete cascade,
  nome      text not null,
  email     text,
  -- nome canônico do gerente, igual ao usado em oportunidades/faturamento/metas
  gerente   text,
  papel     text not null default 'gerente' check (papel in ('gerente','diretor','admin')),
  criado_em timestamptz not null default now()
);

create or replace function public.meu_papel() returns text
language sql stable security definer set search_path = public as
$$ select papel from public.perfis where user_id = auth.uid() $$;

create or replace function public.meu_gerente() returns text
language sql stable security definer set search_path = public as
$$ select gerente from public.perfis where user_id = auth.uid() $$;

create or replace function public.ve_tudo() returns boolean
language sql stable security definer set search_path = public as
$$ select coalesce((select papel in ('diretor','admin') from public.perfis where user_id = auth.uid()), false) $$;

-- ---------------------------------------------------------------------------
-- Clientes
-- ---------------------------------------------------------------------------
create table if not exists public.clientes (
  id                 text primary key,           -- slug do nome
  nome               text not null,
  gerente            text,
  segmento           text,
  cnpj               text,
  contato            text,
  siglas_faturamento text[] not null default '{}', -- como o cliente aparece na planilha de faturamento
  origem             text not null default 'crm',
  atualizado_em      timestamptz not null default now(),
  atualizado_por     uuid references auth.users(id)
);

-- ---------------------------------------------------------------------------
-- Oportunidades
-- ---------------------------------------------------------------------------
create table if not exists public.oportunidades (
  numero              bigint generated by default as identity (start with 7000) primary key,
  gerente             text not null,
  cliente_id          text references public.clientes(id) on update cascade,
  cliente             text not null,
  status              text not null check (status in (
                        'Qualificação','Orçamento','Proposta','Forecast','Negociação',
                        'Encerrada - Ganha','Encerrada - Perdida','Encerrada - Abandonada',
                        'Encerrada - Encerrada pelo Sistema')),
  titulo              text not null,
  area                text,
  revenda             text,
  software            text,        -- fabricante
  parceiro            text,
  cadastro            date,
  fechamento          date,
  probabilidade       int check (probabilidade between 0 and 100),
  valor_total         numeric not null default 0,
  valor_servico       numeric not null default 0,
  valor_software      numeric not null default 0,
  faturamento_servico numeric not null default 0,  -- faturamento de serviço no ano
  software_ano        numeric not null default 0,  -- software no ano
  desc_servico        text,
  desc_produto        text,
  observacoes         text,
  origem              text not null default 'crm',
  atualizado_em       timestamptz not null default now(),
  atualizado_por      uuid references auth.users(id)
);
create index if not exists oportunidades_gerente_idx on public.oportunidades (gerente);
create index if not exists oportunidades_fechamento_idx on public.oportunidades (fechamento);

-- Histórico de mudanças de etapa (base para "o que mudou" e conversão histórica)
create table if not exists public.oportunidades_historico (
  id          bigint generated always as identity primary key,
  numero      bigint not null references public.oportunidades(numero) on delete cascade,
  status_de   text,
  status_para text,
  valor_ano   numeric,
  em          timestamptz not null default now(),
  por         uuid references auth.users(id)
);

create or replace function public.registrar_historico() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status
     or (new.faturamento_servico + new.software_ano) is distinct from (old.faturamento_servico + old.software_ano) then
    insert into public.oportunidades_historico (numero, status_de, status_para, valor_ano, por)
    values (new.numero, case when tg_op = 'UPDATE' then old.status end, new.status,
            new.faturamento_servico + new.software_ano, auth.uid());
  end if;
  return new;
end $$;

drop trigger if exists oportunidades_historico_trg on public.oportunidades;
create trigger oportunidades_historico_trg
  after insert or update on public.oportunidades
  for each row execute function public.registrar_historico();

-- ---------------------------------------------------------------------------
-- Faturamento (carregado da aba Consolidado pela importação)
-- ---------------------------------------------------------------------------
create table if not exists public.faturamento (
  id         bigint generated always as identity primary key,
  mes        text not null,     -- AAAA-MM do mês de emissão
  gerente    text,
  cliente    text,
  cliente_id text,
  projeto    text,
  tipo       text,
  tecnologia text,
  bu         text,
  territorio text,
  contrato   text,
  nf         text,
  status     text,              -- Emitida / Sem status
  valor      numeric not null,
  carga      text               -- identifica a importação
);
create index if not exists faturamento_mes_idx on public.faturamento (mes);
create index if not exists faturamento_gerente_idx on public.faturamento (gerente);

-- ---------------------------------------------------------------------------
-- Metas e Running previsto
-- ---------------------------------------------------------------------------
create table if not exists public.metas (
  gerente text not null,
  ano     int  not null,
  valor   numeric not null,
  inicio  date,
  fim     date,
  primary key (gerente, ano)
);

create table if not exists public.running_previsto (
  chave          text primary key,   -- "<gerentes separados por |>@<ano>" ou "todos@<ano>"
  valor          numeric not null default 0,
  atualizado_em  timestamptz not null default now(),
  atualizado_por uuid references auth.users(id)
);

-- ---------------------------------------------------------------------------
-- Segurança (RLS)
--   gerente: vê e edita só a própria carteira; vê o próprio faturamento
--   diretor/admin: vê tudo; admin também apaga
-- ---------------------------------------------------------------------------
alter table public.perfis                  enable row level security;
alter table public.clientes                enable row level security;
alter table public.oportunidades           enable row level security;
alter table public.oportunidades_historico enable row level security;
alter table public.faturamento             enable row level security;
alter table public.metas                   enable row level security;
alter table public.running_previsto        enable row level security;

drop policy if exists perfis_ler on public.perfis;
create policy perfis_ler on public.perfis for select to authenticated
  using (user_id = auth.uid() or public.ve_tudo());
drop policy if exists perfis_admin on public.perfis;
create policy perfis_admin on public.perfis for all to authenticated
  using (public.meu_papel() = 'admin') with check (public.meu_papel() = 'admin');

drop policy if exists clientes_ler on public.clientes;
create policy clientes_ler on public.clientes for select to authenticated using (true);
drop policy if exists clientes_inserir on public.clientes;
create policy clientes_inserir on public.clientes for insert to authenticated with check (true);
drop policy if exists clientes_editar on public.clientes;
create policy clientes_editar on public.clientes for update to authenticated
  using (public.ve_tudo() or gerente = public.meu_gerente() or gerente is null or gerente = '');
drop policy if exists clientes_apagar on public.clientes;
create policy clientes_apagar on public.clientes for delete to authenticated using (public.meu_papel() = 'admin');

drop policy if exists opps_ler on public.oportunidades;
create policy opps_ler on public.oportunidades for select to authenticated
  using (public.ve_tudo() or gerente = public.meu_gerente());
drop policy if exists opps_inserir on public.oportunidades;
create policy opps_inserir on public.oportunidades for insert to authenticated
  with check (public.ve_tudo() or gerente = public.meu_gerente());
drop policy if exists opps_editar on public.oportunidades;
create policy opps_editar on public.oportunidades for update to authenticated
  using (public.ve_tudo() or gerente = public.meu_gerente())
  with check (public.ve_tudo() or gerente = public.meu_gerente());
drop policy if exists opps_apagar on public.oportunidades;
create policy opps_apagar on public.oportunidades for delete to authenticated using (public.meu_papel() = 'admin');

drop policy if exists hist_ler on public.oportunidades_historico;
create policy hist_ler on public.oportunidades_historico for select to authenticated
  using (public.ve_tudo() or exists (select 1 from public.oportunidades o where o.numero = oportunidades_historico.numero and o.gerente = public.meu_gerente()));

drop policy if exists fat_ler on public.faturamento;
create policy fat_ler on public.faturamento for select to authenticated
  using (public.ve_tudo() or gerente = public.meu_gerente());

drop policy if exists metas_ler on public.metas;
create policy metas_ler on public.metas for select to authenticated using (true);
drop policy if exists metas_admin on public.metas;
create policy metas_admin on public.metas for all to authenticated
  using (public.meu_papel() = 'admin') with check (public.meu_papel() = 'admin');

drop policy if exists running_ler on public.running_previsto;
create policy running_ler on public.running_previsto for select to authenticated using (true);
drop policy if exists running_gravar on public.running_previsto;
create policy running_gravar on public.running_previsto for all to authenticated
  using (public.ve_tudo() or chave = public.meu_gerente() || '@' || split_part(chave, '@', 2))
  with check (public.ve_tudo() or chave = public.meu_gerente() || '@' || split_part(chave, '@', 2));

